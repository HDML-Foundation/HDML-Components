/**
 * ★ **`04-grouped-stacked` — the densest page in the corpus, and
 * the only one Slice G owns end to end** (RFC §10.1 G, SPEC §7).
 *
 * Five views over **one** frame, and between them they write every
 * clause the two layout containers landed with:
 *
 * - **A** — `hdml-cluster` over three bars: R19's subdivision on a
 *   real page, three slots rather than the fixture's two, and over
 *   an outer band the page declares at `--hdml-bandwidth: 0.75`
 *   rather than the registered initial `0.8`;
 * - **B** — the same three children under `hdml-stack`, so grouped
 *   ↔ stacked really is one tag rename, and the baseline derive runs
 *   for the first time over a **delivered** `Float64Array`;
 * - **C** — `offset="normalize"` against an authored `min="0"
 *   max="1"`;
 * - **D** — three `hdml-area`s, with `--hdml-curve-type: natural`
 *   declared **on the stack** — finding 23's claim, on a page;
 * - **E** — two `hdml-stack`s inside one `hdml-cluster`: V17's only
 *   legal nesting, and the case that forces the container-hoisted
 *   channel to be **transitive**, because the two inner stacks bind
 *   nothing at all.
 *
 * ★ **Nothing under `html/hdvl/` had ever run a container** before
 * this gate. Slice G's arithmetic was proved by twenty-one
 * fixtures in two files, and a fixture proves the shape you
 * thought of; a corpus page proves the shape the author wrote.
 *
 * ★ **A bar's `w` is not `bandOf().width`.** `mark-bar.ts` projects
 * the band's two edges through `Projection.point` and takes their
 * difference, which is what makes it plane-agnostic — so on a band
 * whose arithmetic is not dyadic, `(start + width) − start` differs
 * from `width` in the last ulps. The tiling assertions are therefore
 * `strictEqual` on the **low edge**, which lands exactly, and rule
 * 3's `closeTo` on the far one. The band seam is bit-exact only
 * where the arithmetic is, and `W = 544`, `n = 12`, `b = 0.75`
 * makes no edge of this page a dyadic rational.
 *
 * ★ **C3 is discharged here** (step 32). Every one of the five views
 * declares an `hdml-legend`, and until Slice H landed one every
 * golden on this page was taken over {@link withoutDeferred}'s
 * restriction. `DEFERRED_TO_SLICE_H` is now **empty**, the five
 * goldens carry their legend group, and the test asserts both halves
 * the other way round: the view declares one legend, and the
 * compared scene carries exactly one legend group. The goldens grew
 * by six nodes each and **not one mark coordinate moved** — the
 * `git diff` that landed them has no deletion in it.
 *
 * ★ **The key is the scale's domain, not the marks'.** All three
 * series render here, so this page cannot tell the two apart; `12-C`
 * can, and does (a `hidden` series keeps its entry).
 */

