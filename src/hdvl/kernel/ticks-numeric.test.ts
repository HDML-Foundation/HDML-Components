/**
 * RFC §4.8 — the normative tick ladders, and §4.2 step 5's `nice`.
 *
 * A pure fixture table: no DOM, no computed style, no element, no
 * `fixture` import and no `await`. That is the module's own
 * invariant, and the grep
 * `grep -rn "document\.\|window\." src/hdvl/kernel/` is what keeps
 * it true.
 *
 * **Which cross-engine rule applies where** (plan rules 1, 2, 9):
 *
 * - Everything the integer-reciprocal form makes exact — `i /
 *   divisor`, `i · step` at a non-negative power, the `{1, 2, 5}`
 *   multiplier itself — is asserted with **exact `deepEqual`**.
 *   A `closeTo` here would discard the entire reason §4.8
 *   specifies the divisor form.
 * - `Math.pow(base, p)` for a small integer `p` is exact on all
 *   three engines, so the log ladder's powers are asserted
 *   **exactly** too. That is the one place rules 1 and 2 touch,
 *   and it is deliberate rather than an oversight: the ladder
 *   emits `base^p` and `k · base^p`, never a value that has been
 *   through `Math.log` on the way out. `logBase` is used only to
 *   pick the integer exponents.
 * - No assertion in this file needed `closeTo`.
 */

